# Exp-06: List Methods

numbers = [10, 20, 30]

print("Original List:", numbers)

# Add using insert()
numbers.insert(1, 15)
print("After Add:", numbers)

# Append
numbers.append(40)
print("After Append:", numbers)

# Extend
numbers.extend([50, 60])
print("After Extend:", numbers)

# Delete
numbers.remove(20)
print("After Delete:", numbers)